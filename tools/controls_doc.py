"""Writes the controls tables in docs/controls.md from the game's input map.

The bindings come from ``game/project.godot`` and the rows, labels and contexts from
``game/core/input/controls.json``, the same data the in-game Controls tab reads, so the doc
cannot drift from the game. Only the text between the two markers is generated; the prose
around it is kept.

    uv run python controls_doc.py           # rewrite the doc
    uv run python controls_doc.py --check   # exit 1 when the committed doc is stale (CI)
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROJECT = ROOT / "game" / "project.godot"
CONTROLS = ROOT / "game" / "core" / "input" / "controls.json"
DOC = ROOT / "docs" / "controls.md"
BEGIN = "<!-- controls:begin (generated by tools/controls_doc.py; edit controls.json) -->"
END = "<!-- controls:end -->"
CONTEXT_ORDER = ["foot", "drive", "fly", "any", "debug"]

# Names match Controls.event_text in game/core/input/controls.gd (a gdUnit test compares them).
PAD_BUTTONS = {
    0: "A",
    1: "B",
    2: "X",
    3: "Y",
    4: "View",
    5: "Guide",
    6: "Menu",
    7: "L3",
    8: "R3",
    9: "LB",
    10: "RB",
    11: "D-pad up",
    12: "D-pad down",
    13: "D-pad left",
    14: "D-pad right",
}
PAD_AXES = {0: "left stick", 1: "left stick", 2: "right stick", 3: "right stick", 4: "LT", 5: "RT"}
MOUSE = {1: "left click", 2: "right click", 3: "middle click"}
SPECIAL_KEYS = {
    4194305: "Esc",
    4194306: "Tab",
    4194308: "Backspace",
    4194309: "Enter",
    4194325: "Shift",
    4194319: "Left",
    4194321: "Right",
    4194326: "Ctrl",
    4194328: "Alt",
}
F1 = 4194332


def key_name(code: int) -> str:
    if code in SPECIAL_KEYS:
        return SPECIAL_KEYS[code]
    if F1 <= code < F1 + 12:
        return f"F{code - F1 + 1}"
    if 32 < code < 127:
        return chr(code).upper()
    if code == 32:
        return "Space"
    return f"key {code}"


def parse_input_map(text: str) -> dict[str, list[tuple[str, str]]]:
    """Action -> [(kind, name)] with kind 'pad' or 'key', in project.godot order."""
    section = text.split("[input]", 1)[1].split("\n[", 1)[0]
    actions: dict[str, list[tuple[str, str]]] = {}
    for m in re.finditer(r"^(\w+)=\{(.*?)^\}", section, re.DOTALL | re.MULTILINE):
        events: list[tuple[str, str]] = []
        for chunk in m.group(2).split("Object(")[1:]:
            kind, body = chunk.split(",", 1)

            def field(name: str, body: str = body) -> float:
                return float(re.search(rf'"{name}":(-?[\d.]+)', body).group(1))

            if kind == "InputEventJoypadButton":
                i = int(field("button_index"))
                events.append(("pad", PAD_BUTTONS.get(i, f"button {i}")))
            elif kind == "InputEventJoypadMotion":
                a = int(field("axis"))
                events.append(("pad", PAD_AXES.get(a, f"axis {a}")))
            elif kind == "InputEventMouseButton":
                b = int(field("button_index"))
                events.append(("key", MOUSE.get(b, f"mouse {b}")))
            elif kind == "InputEventKey":
                code = int(field("physical_keycode")) or int(field("keycode"))
                events.append(("key", key_name(code)))
        actions[m.group(1)] = events
    return actions


def binding_text(bindings: dict[str, list[tuple[str, str]]], action: str, kind: str) -> str:
    names: list[str] = []
    for k, name in bindings.get(action, []):
        if k == kind and name not in names:
            names.append(name)
    return " or ".join(names)


def row_text(row: dict, bindings: dict[str, list[tuple[str, str]]], kind: str) -> str:
    if kind in row:
        return row[kind]
    action = row.get("action") or row["actions"][0]
    text = binding_text(bindings, action, kind)
    if not text:
        return "-"
    return f"hold {text}" if row.get("hold") else text


def tables(controls: dict, bindings: dict[str, list[tuple[str, str]]]) -> str:
    out: list[str] = []
    for ctx in CONTEXT_ORDER:
        rows = [r for r in controls["rows"] if r["context"] == ctx and not r.get("reserved")]
        if not rows:
            continue
        out.append(f"### {controls['contexts'][ctx]}")
        out.append("")
        out.append("| action | controller | keyboard and mouse |")
        out.append("|---|---|---|")
        for r in rows:
            pad = row_text(r, bindings, "pad")
            key = row_text(r, bindings, "key")
            out.append(f"| {r['label']} | {pad} | {key} |")
        out.append("")
    return "\n".join(out).rstrip("\n")


def render(doc: str, generated: str) -> str:
    if BEGIN not in doc or END not in doc:
        raise SystemExit(f"{DOC} has no controls markers")
    head, rest = doc.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{BEGIN}\n{generated}\n{END}{tail}"


def build() -> str:
    controls = json.loads(CONTROLS.read_text())
    bindings = parse_input_map(PROJECT.read_text())
    return render(DOC.read_text(), tables(controls, bindings))


USAGE = "usage: uv run python controls_doc.py [--check]"


def main(argv: list[str]) -> int:
    unknown = [a for a in argv if a != "--check"]
    if unknown:
        print(f"unknown argument {' '.join(unknown)}; {USAGE}", file=sys.stderr)
        return 2
    new = build()
    if "--check" in argv:
        if new != DOC.read_text():
            print(
                f"{DOC.relative_to(ROOT)} is stale: run `uv run python controls_doc.py` in tools/"
            )
            return 1
        print(f"{DOC.relative_to(ROOT)} matches the input map")
        return 0
    DOC.write_text(new)
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
